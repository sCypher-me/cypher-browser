    dialog.showSaveDialog = async () => ({ canceled:false,filePath:modPath });
    await invoke('mod:export');
    dialog.showSaveDialog = originalSave;
    const exportedMod = JSON.parse(fs.readFileSync(modPath,'utf8'));
    assert.equal(exportedMod.settings.home.widgets.length,6);
    assert.ok(!fs.readFileSync(modPath,'utf8').includes('My private note'),'export excludes personal notes');
    await pause(350);
    fs.writeFileSync(path.join(screenshots,'cypher-home-widgets.png'),(await win.webContents.capturePage()).toPNG());
    const base = `http://127.0.0.1:${server.address().port}`;
    await invoke('navigate', base + '/page-a');
    await until(async () => (await invoke('state')).tabs[0].title === 'Cypher /page-a' && !(await invoke('state')).tabs[0].loading, 'page A');
    let view = win.contentView.children.find(v => v.webContents && v.webContents !== win.webContents);
    assert.ok(view, 'native page view exists');
    assert.equal(await view.webContents.executeJavaScript('typeof require'), 'undefined');
    assert.equal(await view.webContents.executeJavaScript('typeof window.cypher'), 'undefined');
    assert.ok(view.getBounds().x > 200);
    await invoke('media:window:toggle');
    await until(() => BrowserWindow.getAllWindows().length === 2, 'floating miniplayer');
    const miniPlayer = BrowserWindow.getAllWindows().find(window => window !== win);
    await until(() => miniPlayer.webContents.getURL().endsWith('#mini-player') && !miniPlayer.webContents.isLoading(), 'miniplayer renderer');
    assert.equal(miniPlayer.isAlwaysOnTop(),true,'miniplayer floats above the browser');
    assert.equal(view.getVisible(),true,'opening the player leaves the current page visible');
    await miniPlayer.webContents.executeJavaScript('document.querySelector(".mini-player-close").click()');
    await until(() => !miniPlayer.isVisible(),'miniplayer closes without hiding the page');
    await invoke('bookmark:toggle');
    assert.equal((await invoke('state')).bookmarks.length,1);
    await invoke('navigate',base + '/page-b');
    await until(async () => (await invoke('state')).tabs[0].title === 'Cypher /page-b', 'page B');
    assert.equal((await invoke('state')).tabs[0].canGoBack,true);
    await invoke('back');
    await until(async () => (await invoke('state')).tabs[0].url === base + '/page-a', 'back');
    await invoke('settings',{ tabPosition:'top' });
    await until(() => win.webContents.executeJavaScript('!!document.querySelector(".horizontal-tabs")'), 'top tabs');
    await until(() => view.getBounds().x < 100, 'native view follows layout');
    await invoke('settings',{ tabPosition:'side' });
    await invoke('tab:new',{ url:base + '/private',private:true });
    await until(async () => (await invoke('state')).tabs.some(t => t.title === 'Cypher /private'), 'private tab');
    state = await invoke('state');
    assert.ok(!state.history.some(h => h.url.includes('/private')));
    assert.deepEqual(state.homeData.notes,{},'private tabs do not receive saved notes');
    await invoke('home:note',{ id:note.id,text:'private replacement' });
    const privateView = win.contentView.children.find(v => v.webContents?.getURL().includes('/private'));
    await privateView.webContents.executeJavaScript('localStorage.setItem("private-test","yes")');
    assert.notEqual(privateView.webContents.session, view.webContents.session);
